#[cfg(test)]
mod tests {
    use super::{Colormap, FIRE_LUT, VIRIDIS_LUT};

    #[test]
    fn event_polarity_keeps_separate_channels() {
        let color = Colormap::EventPolarity.map(0.75, 0.25);
        assert!(color.g() > color.r());
    }

    #[test]
    fn single_channel_colormaps_use_combined_intensity() {
        let color = Colormap::Viridis.map(0.5, 0.25);
        assert!(color.r() > 0 || color.g() > 0 || color.b() > 0);
    }

    #[test]
    fn viridis_matches_reference_points() {
        assert_eq!(VIRIDIS_LUT[0], [68, 1, 84]);
        assert_eq!(VIRIDIS_LUT[128], [33, 145, 140]);
        assert_eq!(VIRIDIS_LUT[255], [253, 231, 37]);
    }

    #[test]
    fn fire_matches_reference_endpoints() {
        assert_eq!(FIRE_LUT[0], [0, 0, 0]);
        assert_eq!(FIRE_LUT[255], [255, 255, 255]);
    }
}
