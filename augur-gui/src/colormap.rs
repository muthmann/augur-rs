use egui::Color32;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Colormap {
    EventPolarity,
    Fire,
    Grayscale,
    Viridis,
    Magma,
    Inferno,
}

impl Default for Colormap {
    fn default() -> Self {
        Self::EventPolarity
    }
}

impl Colormap {
    pub const ALL: [Self; 6] = [
        Self::EventPolarity,
        Self::Fire,
        Self::Grayscale,
        Self::Viridis,
        Self::Magma,
        Self::Inferno,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Self::EventPolarity => "Event polarity",
            Self::Fire => "Fire",
            Self::Grayscale => "Grayscale",
            Self::Viridis => "Viridis",
            Self::Magma => "Magma",
            Self::Inferno => "Inferno",
        }
    }

    pub fn map(self, on_norm: f32, off_norm: f32) -> Color32 {
        match self {
            Self::EventPolarity => Color32::from_rgb(
                channel_to_u8(off_norm).max(8),
                channel_to_u8(on_norm).max(8),
                8,
            ),
            _ => {
                let intensity = (on_norm + off_norm).clamp(0.0, 1.0);
                let [r, g, b] = sample_lut(self.lut(), intensity);
                Color32::from_rgb(r, g, b)
            }
        }
    }

    fn lut(self) -> &'static [[u8; 3]; 256] {
        match self {
            Self::EventPolarity => &GRAYSCALE_LUT,
            Self::Fire => &FIRE_LUT,
            Self::Grayscale => &GRAYSCALE_LUT,
            Self::Viridis => &VIRIDIS_LUT,
            Self::Magma => &MAGMA_LUT,
            Self::Inferno => &INFERNO_LUT,
        }
    }
}

fn channel_to_u8(value: f32) -> u8 {
    (value.clamp(0.0, 1.0) * 255.0).round() as u8
}

fn sample_lut(lut: &[[u8; 3]; 256], value: f32) -> [u8; 3] {
    lut[(value.clamp(0.0, 1.0) * 255.0).round() as usize]
}

